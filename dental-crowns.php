                                    <strong>How do Bridges Work?</strong><br/>

                                    A bridge may be recommended if you're missing one or more teeth. Gaps left by missing teeth eventually cause the remaining teeth to rotate or shift into the empty spaces, resulting in a bad bite. The imbalance caused by missing teeth can also lead to gum disease and temporomandibular joint (TMJ) disorders. 

                                    Bridges are commonly used to replace one or more missing teeth. They span the space where the teeth are missing. Bridges are cemented to the natural teeth or implants surrounding the empty space. These teeth, called abutments, serve as anchors for the bridge. A replacement tooth, called a pontic, is attached to the crowns that cover the abutments. As with crowns, you have a choice of materials for bridges. Your dentist can help you decide which to use, based on the location of the missing tooth (or teeth), its function, aesthetic considerations and cost. <br/>


