                            teeth and discuss with you what your dream smile is. </li>
                        <li><strong>Digital scanning and treatment planning:</strong> A digital scan is done, which
                            helps create a digital model of your teeth that predicts future movement.</li>
                        <li><strong>Creation of aligners:</strong> The creation of Invisaligns is done based on the
                            planned movement of teeth.</li>
                        <li><strong>Invisalign treatment stages:</strong> The patient is required to wear each
                            Invisalign for 20-22 hours a day, after which a new set is worn every week or two.</li>
                    </ul>

