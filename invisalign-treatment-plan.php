                    <h3>How the Invisalign Treatment Process Works</h3>
                    <p>The Invisalign treatment process begins by visiting a professional for a consultation and
                        scanning your teeth. The process is different from the conventional moulds that dentists use to
                        take impressions of your mouth. The latest technology allows for a precise 3D image of your
                        mouth. The dentist can then use this 3D image to create a plan that illustrates how your teeth
                        will shift at different stages during the treatment process. </p>

                    <ul> <strong>The process involves:</strong>
                        <li>Scanning your teeth digitally</li>
                        <li>Creating a treatment plan using orthodontic software</li>
                        <li>Creating a set of clear aligners specifically for your teeth</li>
                        <li>Monitors your progress during the treatment process.</li>

                    </ul>
